def holds(expr: str, flags: dict[str, Any]) -> bool:
    """깃발 식 평가. 모르는 깃발은 KeyError(지침 오타를 테스트에서 잡는다)."""
    expr = expr.strip()
    if not expr:
        return True
    return any(all(_atom(a, flags) for a in alt.split(" and ")) for alt in expr.split(" or "))


def _atom(a: str, flags: dict[str, Any]) -> bool:
    a = a.strip()
    if a.startswith("not "):
        return not bool(flags[a[4:].strip()])
    return bool(flags[a])


