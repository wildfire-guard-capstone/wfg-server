def active(item_id: str, flags: dict[str, Any]) -> list[Line]:
    return [ln for ln in GUIDES.get(item_id, []) if holds(ln.when, flags)]


def extra_topics(item_id: str, flags: dict[str, Any]) -> list[str]:
    return list(
        dict.fromkeys(ln.topic for ln in active(item_id, flags) if ln.kind == "extra" and ln.topic)
    )


def queries(item_id: str, flags: dict[str, Any]) -> list[str]:
    return [ln.q for ln in active(item_id, flags) if ln.q]


def render(item_id: str, flags: dict[str, Any]) -> str:
    lines = active(item_id, flags)
    do = [ln.text for ln in lines if ln.kind == "do"]
    extra = [f"{ln.text} (주제 「{ln.topic}」)" for ln in lines if ln.kind == "extra"]
    avoid = [ln.text for ln in lines if ln.kind == "avoid"]
    out = []
    if do:
        out.append("쓸 것:\n" + "\n".join(f"- {t}" for t in do))
    if extra:
        out.append(
            "이번 상황에 덧붙일 제안(근거 발췌에 그 조치가 있을 때만, 주제마다 하나):\n"
            + "\n".join(f"- {t}" for t in extra)
        )
    if avoid:
        out.append("이번 상황에서 쓰지 않을 것:\n" + "\n".join(f"- {t}" for t in avoid))
    return "\n".join(out)
