"""Lock the development / hold-out split of AI Hub cases (PD-08).

Selection: grade A perimeters and at least MIN_AREA_HA (5 ha, the NIFoS "medium fire"
threshold). Below that a fire covers fewer than ~55 cells of 30 m, so IoU measures the
pixel staircase more than the model; those cases are listed separately.

Split: stratified by size class, seeded random, about 30 % hold-out. Cases already looked
at during development (the pilot scenario) can never go to hold-out. The hold-out list is
hashed; it is opened once, after calibration (plan step 4-3).

Usage:
  python -m evaluation.split --grades results/aihub_grades.csv --out evaluation/scenarios
"""

import argparse
import csv
import hashlib
import random
from datetime import date
from pathlib import Path

MIN_AREA_HA = 5.0
HOLDOUT_FRACTION = 0.3
SEED = 20261004
SIZE_CLASSES = [("small", 5.0, 20.0), ("medium", 20.0, 100.0), ("large", 100.0, float("inf"))]
MIN_LARGE_HOLDOUT = 2


def size_class(area_ha: float) -> str:
    for name, lo, hi in SIZE_CLASSES:
        if lo <= area_ha < hi:
            return name
    raise ValueError(area_ha)


def ids_hash(ids: list[str]) -> str:
    return hashlib.sha256("\n".join(sorted(ids)).encode()).hexdigest()[:16]


def split(rows: list[dict], dev_only: set[str]) -> tuple[list[dict], list[dict], list[dict]]:
    eligible = [
        r for r in rows if r["grade"] == "A" and float(r["repaired_area_ha"]) >= MIN_AREA_HA
    ]
    small = [r for r in rows if r["grade"] == "A" and float(r["repaired_area_ha"]) < MIN_AREA_HA]
    rng = random.Random(SEED)
    dev, holdout = [], []
    for name, _, _ in SIZE_CLASSES:
        group = sorted(
            (r for r in eligible if size_class(float(r["repaired_area_ha"])) == name),
            key=lambda r: r["case_id"],
        )
        n_hold = round(len(group) * HOLDOUT_FRACTION)
        if name == "large":
            n_hold = max(n_hold, MIN_LARGE_HOLDOUT)
        candidates = [r for r in group if r["case_id"] not in dev_only]
        picked = {r["case_id"] for r in rng.sample(candidates, min(n_hold, len(candidates)))}
        holdout += [r for r in group if r["case_id"] in picked]
        dev += [r for r in group if r["case_id"] not in picked]
    return dev, holdout, small


def write_scenario(path: Path, name: str, rows: list[dict], note: str) -> str:
    h = ids_hash([r["case_id"] for r in rows])
    lines = [
        f"# {name}: {note}",
        f"# Generated by evaluation/split.py on {date.today().isoformat()} — do not edit by hand.",
        f"# selection: grade A, area >= {MIN_AREA_HA} ha · seed {SEED} · "
        f"hold-out {HOLDOUT_FRACTION:.0%} per size class",
        "",
        f"name: {name}",
        "dataset: aihub",
        f"ids_sha256_16: {h}",
        "",
        "cases:",
    ]
    for r in sorted(rows, key=lambda r: float(r["repaired_area_ha"])):
        lines.append(
            f"  - id: {r['case_id']}   # {float(r['repaired_area_ha']):.1f} ha, "
            f"{float(r['duration_h']):.1f} h, {size_class(float(r['repaired_area_ha']))}"
            if float(r["repaired_area_ha"]) >= MIN_AREA_HA
            else f"  - id: {r['case_id']}   # {float(r['repaired_area_ha']):.1f} ha"
        )
    path.write_text("\n".join(lines) + "\n")
    return h


def read_ids(scenario: Path) -> set[str]:
    return {
        s.split(":", 1)[1].split("#")[0].strip()
        for s in (line.strip() for line in scenario.read_text().splitlines())
        if s.startswith("- id:")
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--grades", type=Path, default=Path("results/aihub_grades.csv"))
    ap.add_argument("--out", type=Path, default=Path("evaluation/scenarios"))
    args = ap.parse_args()

    rows = list(csv.DictReader(args.grades.open()))
    dev_only = read_ids(args.out / "pilot.yaml")
    dev, holdout, small = split(rows, dev_only)
    hd = write_scenario(args.out / "dev.yaml", "dev", dev, "development and calibration cases")
    hh = write_scenario(
        args.out / "holdout.yaml", "holdout", holdout, "LOCKED — open once after calibration"
    )
    write_scenario(args.out / "small.yaml", "small", small, f"grade A below {MIN_AREA_HA} ha")
    print(f"dev {len(dev)} ({hd}) · holdout {len(holdout)} ({hh}) · small {len(small)}")


if __name__ == "__main__":
    main()
